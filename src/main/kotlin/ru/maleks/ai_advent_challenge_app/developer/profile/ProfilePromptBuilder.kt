package ru.maleks.ai_advent_challenge_app.developer.profile

class ProfilePromptBuilder {

    fun build(
        profile: AssistantProfile,
        task: String,
        context: ProfileContext
    ): String {
        return """
            ${profile.instruction}

            ================================================================
            ЗАДАЧА ПОЛЬЗОВАТЕЛЯ
            ================================================================
            $task

            ================================================================
            GIT STATUS
            ================================================================
            ${context.gitStatus}

            ================================================================
            ЗАВИСИМОСТИ И КОНФИГУРАЦИЯ
            ================================================================
            ${context.dependencies}

            ================================================================
            РЕЛЕВАНТНАЯ ДОКУМЕНТАЦИЯ
            ================================================================
            ${context.relevantDocumentation}

            ================================================================
            РЕЛЕВАНТНЫЙ КОД
            ================================================================
            ${context.relevantCode}

            ================================================================
            ДОСТУПНЫЕ ЛОГИ
            ================================================================
            ${context.recentLogs}

            ================================================================
            РЕЗУЛЬТАТ ПРОВЕРКИ ТЕСТОВ
            ================================================================
            ${context.testResult}

            Используй только факты из переданного контекста. Не утверждай, что изменил файлы:
            ты выдаёшь точный результат, который разработчик может применить и проверить.
        """.trimIndent()
    }
}
